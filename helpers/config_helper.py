def load_dashboards_from_file():
    try:
        with open(dashboards_json_path, 'r') as f:
            data = json.load(f)
            return data if isinstance(data, list) else [data]
    except (FileNotFoundError, json.JSONDecodeError):
        return []

def save_dashboards_to_file(data):
    with open(dashboards_json_path, 'w') as f:
        json.dump(data, f, indent=2)

def discover_metric_keys():
    """Scan every count across every dashboard for the top-level and filter keys
    that have ever been used, so the editor can suggest keys the user hasn't added yet."""
    top_level_keys = set()
    filter_keys = set()
    for dashboard in load_dashboards_from_file():
        for count in dashboard.get("visualization_types", {}).get("counts", []):
            if not isinstance(count, dict):
                continue
            top_level_keys.update(k for k in count.keys() if k not in ("id", "name", "filters"))
            filters = count.get("filters")
            if isinstance(filters, dict):
                filter_keys.update(filters.keys())
    return {"top_level": sorted(top_level_keys), "filters": sorted(filter_keys)}

def discover_chart_keys():
    """Scan every chart item across every section/dashboard for the top-level keys used,
    and the filter keys used per chart 'type', so suggestions can be tailored to the
    chart type currently being edited."""
    top_level_keys = set()
    by_type = {}
    for dashboard in load_dashboards_from_file():
        sections = dashboard.get("visualization_types", {}).get("charts", {}).get("sections", [])
        for section in sections:
            for item in section.get("items", []):
                if not isinstance(item, dict):
                    continue
                top_level_keys.update(k for k in item.keys() if k not in ("id", "name", "type", "filters"))
                chart_type = item.get("type")
                filters = item.get("filters")
                if chart_type and isinstance(filters, dict):
                    by_type.setdefault(chart_type, set()).update(filters.keys())
    return {
        "top_level": sorted(top_level_keys),
        "by_type": {t: sorted(keys) for t, keys in by_type.items()},
    }

def _coerce_list(value):
    if value in (None, "", []):
        return []
    if isinstance(value, list):
        return [v for v in value if v not in (None, "")]
    return [value]

def _normalize_filter_value(value):
    if isinstance(value, list):
        cleaned = [v for v in value if v not in (None, "")]
        if not cleaned:
            return []
        return cleaned
    if value in (None, ""):
        return ""
    return value

def _safe_json_loads(raw_value, default):
    if raw_value in (None, "", []):
        return default
    if isinstance(raw_value, (dict, list)):
        return raw_value
    try:
        return json.loads(raw_value)
    except (TypeError, json.JSONDecodeError):
        return default

