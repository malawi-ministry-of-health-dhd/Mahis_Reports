def _list_ssh_keys():
    """Return .pem/.cer/.key filenames from the project ssh/ directory."""
    if not os.path.isdir(_ssh_dir):
        return []
    return sorted(
        f for f in os.listdir(_ssh_dir)
        if f.endswith(('.pem', '.cer', '.key'))
    )


